/*
 * 微信 UI scope cleanup
 *
 * 只做 UI 隐藏，不删除、迁移或改写任何微信数据。尤其不触碰：
 *   - wxStore.sessions / messages / moments
 *   - 已安装的图片贴纸包（GroupV / GroupAU 挂载区）
 *   - 聊天正文、朋友圈正文及其渲染节点
 *
 * 选择器均限定在微信窗口或已有固定 ID / 导航属性内；不按聊天正文文本匹配。
 */
(function () {
  'use strict';

  var STYLE_ID = 'wx-scope-cleanup-style';
  var ROOT_SELECTOR = '#wx-app-root';

  /*
   * 已审查的稳定 DOM：
   *   #wx-view-discover 内的入口分别由已有 onclick 导航到：
   *   openMomentsPage('全部')、openDiscoverRow('shake')、openDiscoverRow('look')。
   *   其中摇一摇/看一看隐藏整行，而不是删除父分组或改写 onclick，避免影响其他发现功能；
   *   朋友圈入口与朋友圈子页（wx-view-moments-page）不再隐藏，恢复可见。
   *
   * wx-view-my-persona 是已有固定子页 ID。
   * wx-discover-overlay 是 _openDiscoverOverlay 的固定容器；其 title 只在该
   * 浮层的 .wx-header-title 中检查，用于拦截“摇一摇/看一看”子页，不读取聊天正文。
   */
  var HIDE_SELECTORS = [
    '#wx-view-discover .wx-cell[onclick*="openDiscoverRow(\'shake\')"]',
    '#wx-view-discover .wx-cell[onclick*="openDiscoverRow(\'look\')"]',
    '#wx-view-me .wx-cell[onclick*="openMyPersona"]',
    /* Hide the legacy profile header (avatar/nickname/WeChat ID/status) without erasing accountMeta. */
    '#wx-view-me .wx-me-header',
    '#wx-view-my-persona',
    /* 默认 Unicode 表情筛选/字符行；不隐藏 GroupV/GroupAU 图片包挂载区。 */
    '#wx-view-chat-detail #wx-sticker-filter',
    '#wx-view-chat-detail #wx-sticker-grid',
    /* GroupV 的默认 Unicode 心情包入口；不隐藏 GroupAU 的自定义图片贴纸。 */
    '#wx-view-chat-detail .gv-pack-row'
  ];
  var SMS_SELECTORS = [
    /* 已审查的独立短信 UI：隐藏入口和 Unicode 表情行，不触碰短信正文。 */
    '.gd-root[data-gd="sms"] [data-act="drawer-emoji"]',
    '.gd-root[data-gd="sms"] .ba-sms-emoji'
  ];

  function getRoot() {
    return document.querySelector(ROOT_SELECTOR) || document.getElementById('wx-app-root');
  }

  function hideElement(el) {
    if (!el || !el.style) return;
    if (el.getAttribute('data-wx-scope-hidden') !== '1') {
      el.setAttribute('data-wx-scope-hidden', '1');
    }
    el.style.setProperty('display', 'none', 'important');
    el.setAttribute('aria-hidden', 'true');
  }

  function hideKnownNodes(root) {
    if (!root || !root.querySelectorAll) return;
    HIDE_SELECTORS.forEach(function (selector) {
      try {
        root.querySelectorAll(selector).forEach(hideElement);
      } catch (_) {
        /* A selector failure must not affect the rest of the phone UI. */
      }
    });

    /*
     * The overlay has no per-kind ID. Its title is generated by the known
     * _openDiscoverOverlay function, so this exact check is limited to that
     * overlay title node—not arbitrary text in messages, feeds, or chat rows.
     */
    var overlay = root.querySelector('#wx-discover-overlay');
    if (overlay) {
      var title = overlay.querySelector('.wx-header-title');
      var titleText = title && title.textContent ? title.textContent.trim() : '';
      if (titleText === '摇一摇' || titleText === '看一看') {
        hideElement(overlay);
      }
    }
  }

  function hideSmsNodes() {
    SMS_SELECTORS.forEach(function (selector) {
      try { document.querySelectorAll(selector).forEach(hideElement); } catch (_) {}
    });
  }

  function installStyle() {
    if (document.getElementById(STYLE_ID)) return;
    var style = document.createElement('style');
    style.id = STYLE_ID;
    style.textContent = HIDE_SELECTORS.map(function (selector) { return ROOT_SELECTOR + ' ' + selector; }).join(',\n') +
      ',\n' + SMS_SELECTORS.join(',\n') + '{ display: none !important; }';
    (document.head || document.documentElement).appendChild(style);
  }

  function start() {
    installStyle();
    var root = getRoot();
    if (root) hideKnownNodes(root);
    hideSmsNodes();

    var observer = new MutationObserver(function () {
      var currentRoot = getRoot();
      if (currentRoot) hideKnownNodes(currentRoot);
      hideSmsNodes();
    });
    var observeRoot = document.getElementById('sys-app-host') || document.body || document.documentElement;
    if (!observeRoot) return;
    observer.observe(observeRoot, { childList: true, subtree: true });

    /* Keep one explicit handle for diagnostics; it does not alter app data. */
    observeRoot.__wxScopeCleanupObserver = observer;
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start, { once: true });
  } else {
    start();
  }

})();
